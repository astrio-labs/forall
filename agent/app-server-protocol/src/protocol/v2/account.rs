#[derive(Serialize, Deserialize, Debug, Clone, PartialEq, JsonSchema, TS)]
#[serde(tag = "type", rename_all = "camelCase")]
#[ts(tag = "type")]
#[ts(export_to = "v2/")]
pub enum Account {
    #[serde(rename = "apiKey", rename_all = "camelCase")]
    #[ts(rename = "apiKey", rename_all = "camelCase")]
    ApiKey {},

    #[serde(rename = "amazonBedrock", rename_all = "camelCase")]
    #[ts(rename = "amazonBedrock", rename_all = "camelCase")]
    AmazonBedrock {
        #[serde(default = "default_bedrock_credential_source")]
        credential_source: AmazonBedrockCredentialSource,
    },

    /// Managed Forall OAuth account.
    #[serde(rename = "oauth", rename_all = "camelCase")]
    #[ts(rename = "oauth", rename_all = "camelCase")]
    Oauth {
        #[serde(default)]
        email: Option<String>,
        /// Profile display name, when the identity provider supplies one.
        #[serde(default)]
        name: Option<String>,
        #[serde(default)]
        plan_type: Option<PlanType>,
    },
}

fn default_bedrock_credential_source() -> AmazonBedrockCredentialSource {
    AmazonBedrockCredentialSource::AwsManaged
}

impl From<ProviderAccount> for Account {
    fn from(account: ProviderAccount) -> Self {
        match account {
            ProviderAccount::ApiKey => Self::ApiKey {},
            // A `Chatgpt` provider account is how managed Forall OAuth credentials surface
            // from the model-provider layer; expose it on the wire as an `oauth` account.
            ProviderAccount::Chatgpt {
                email,
                name,
                plan_type,
            } => Self::Oauth {
                email,
                name,
                plan_type: Some(plan_type),
            },
            ProviderAccount::AmazonBedrock { credential_source } => {
                Self::AmazonBedrock { credential_source }
            }
        }
    }
}


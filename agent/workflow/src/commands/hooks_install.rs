use std::env;
use std::path::Path;

use crate::active_change::resolve_active_change;
use crate::bootstrap::install_hooks_in_forall_home;
use crate::paths::find_project_root;

pub fn run_hooks_print(cwd: &Path) -> i32 {
    let exe = env::current_exe()
        .map(|p| p.display().to_string())
        .unwrap_or_else(|_| "forall".to_string());

    println!(
        r#"# Forall hook integration (native Rust `forall hook <subcommand>`)

Hooks are installed into ~/.forall/hooks.json (user home, not the repo) by:
  forall hooks install
  forall init

Example wrappers (generated by bootstrap):
  exec "{exe}" hook "pre-tool-use"
  exec "{exe}" hook "post-edit"
  exec "{exe}" hook "post-tool-use-browser"
  exec "{exe}" hook "stop"

Set active change when multiple are open:
  export FORALL_CHANGE=my-feature
  echo my-feature > .forall/workflow/active
"#
    );

    if let Some(root) = find_project_root(cwd) {
        println!("# Detected project root: {}", root.display());
        if let Some(change) = resolve_active_change(&root) {
            println!("# Active change: {change}");
        }
    }

    0
}

pub fn run_hooks_install(_cwd: &Path, _merge_global: bool) -> i32 {
    match install_hooks_in_forall_home() {
        Ok(target) => {
            println!("forall hooks install:");
            println!("  {}", target.display());
            0
        }
        Err(err) => {
            eprintln!("forall hooks install: failed to write hooks.json: {err}");
            1
        }
    }
}
